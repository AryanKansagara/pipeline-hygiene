test('data, rules, approvals and snapshots survive a reload', async ({ page }) => {
  await handOrg(page)
  await page.getByLabel('No activity after (days)').fill('40')
  await tab(page, 'Hygiene')
  await row(page, /^Beta/).getByRole('button', { name: /^Approve/ }).click()
  await expect(page.getByText('1 approved')).toBeVisible()
  await page.getByRole('button', { name: 'Save snapshot' }).click()
  await expect(toastText(page)).toContainText('Saved a snapshot: Week of Nov 6, 2026')
  await page.reload()
  await expect(page.getByText('1 approved')).toBeVisible()
  // Beta idle for 36 days is fine at 40.
  await expect(row(page, /^Beta/)).not.toContainText('No recent activity')
  await tab(page, 'History')
  await expect(page.locator('.snap-list li')).toHaveCount(1)
  // Beta 40: (85+40+100+85)/4 = 77.5.
  await expect(page.locator('.snap-list li')).toContainText('score 78 · commit $140k')
  await tab(page, 'Data & rules')
  await expect(page.getByText('8 opportunities · 18 history changes')).toBeVisible()
})

