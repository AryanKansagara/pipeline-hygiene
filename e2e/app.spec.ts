test('the sample exported as CSV re-imports to the same headline numbers', async ({ page }) => {
  await page.goto('/app?sample=saas')
  const before = await kpis(page)
  await tab(page, 'Data & rules')
  const opps = await downloaded(page, () => page.getByRole('button', { name: 'opportunities.csv' }).click())
  const hist = await downloaded(page, () => page.getByRole('button', { name: 'opportunity-field-history.csv' }).click())
  await newOrg(page)
  await importFile(page, opps.name, opps.text, 'opps')
  await importFile(page, hist.name, hist.text, 'fieldHistory')
  await page.getByLabel('Data as of').fill('2026-11-06')
  await expect(page.getByLabel('Data as of')).toHaveValue('2026-11-06')
  // The sample's own stage benchmarks.
  for (const [stage, days] of [['Prospecting', '21'], ['Qualification', '21'], ['Needs Analysis', '25'], ['Negotiation/Review', '30']]) {
    const f = page.locator('.stage-grid label', { hasText: stage }).locator('input')
    await f.fill(days)
    await expect(f).toHaveValue(days)
  }
  await tab(page, 'Overview')
  expect(await kpis(page)).toEqual(before)
})

