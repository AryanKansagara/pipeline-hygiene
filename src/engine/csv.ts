export interface Table {
  rows: string[][]
  lines: number[]
  /** Row line and opening line of a quote that is never closed. */
  unclosed?: { row: number; line: number }
  /** Line of the last row when the file ends without a line break, as a cut-off file does. */
  openEnd?: number
}

export function parseCsv(text: string, delim?: string): Table {
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1)
  delim ??= sniffDelimiter(text)
  const rows: string[][] = []
  const lines: number[] = []
  let row: string[] = []
  let field = ''
  let quoted = false
  let line = 1
  let rowLine = 1
  let quoteLine = 1
  const t: Table = { rows, lines }
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++ } else quoted = false
      } else {
        if (c === '\n') line++
        field += c
      }
      continue
    }
    if (c === '"' && field === '') { quoted = true; quoteLine = line }
    else if (c === delim) { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field); field = ''
      if (row.some(f => f !== '')) { rows.push(row); lines.push(rowLine) }
      row = []
      line++
      rowLine = line
    } else field += c
  }
  if (quoted) t.unclosed = { row: rowLine, line: quoteLine }
  if (field !== '' || row.length) {
    t.openEnd = rowLine
    row.push(field)
    if (row.some(f => f !== '')) { rows.push(row); lines.push(rowLine) }
  }
  return t
}

/**
 * The separator with the largest table below one of its lines, so a title line above the header does not decide.
 * A line heads a table of itself and every later line with 2 or more cells but no more than it has; ties go to the wider header.
 */
function sniffDelimiter(text: string): string {
  const lines = text.slice(0, 65536)
    .replace(/(^|[\r\n,;|\t])"[^"]*(?:""[^"]*)*"/g, '$1') // Separators inside quotes do not count.
    .split(/[\r\n]+/).filter(l => l.trim()).slice(0, 100)
  let best = ',', rows = 0, width = 0
  for (const d of [',', '\t', ';', '|']) {
    const cells = lines.map(l => l.split(d).length)
    for (let i = 0; i < Math.min(cells.length, 25); i++) {
      if (cells[i] < 2) continue
      const n = cells.slice(i).filter(c => c >= 2 && c <= cells[i]).length
      if (n > rows || (n === rows && cells[i] > width)) { best = d; rows = n; width = cells[i] }
    }
  }
  return best
}

export function toCsv(rows: (string | number)[][]): string {
  return rows.map(r => r.map(v => {
    const s = typeof v === 'number' ? String(Math.round(v * 100) / 100) : v
    return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }).join(',')).join('\r\n') + '\r\n'
}

const FOOTER = /^(grand (sub)?totals?\s*(\(|:|$)|confidential information\b.*do not distribute|copyright\s*(\(c\)|©)\s*\d)/i
const FOOTER_WORD = /^((sub)?totals?( \(\d[\d,]* records?\))?|count|record count|sum|average|avg|max|min|(generated by|filtered by|as of)\b.*)$/i
function isFooter(row: string[]): boolean {
  const cells = row.map(c => c.trim()).filter(Boolean)
  return FOOTER.test(cells[0]) || (cells.length <= 2 && FOOTER_WORD.test(cells[0]))
}

/**
 * Salesforce report exports put a title block above the header and a "Grand Totals" / copyright block below.
 * Finds the first row that looks like a header (3+ non-empty cells, mostly text) and drops footer rows.
 * Only known footer lines are dropped: a sparse row at the end can be a record.
 */
export function findHeaderRow(t: Table): Table {
  let start = 0
  for (let i = 0; i < Math.min(t.rows.length, 25); i++) {
    const cells = t.rows[i].filter(c => c.trim())
    if (cells.length >= 3 && cells.filter(c => /[a-z]/i.test(c) && !/^\d/.test(c)).length >= cells.length * 0.7) { start = i; break }
  }
  let end = t.rows.length
  while (end > start + 1 && isFooter(t.rows[end - 1])) end--
  return { ...t, rows: t.rows.slice(start, end), lines: t.lines.slice(start, end) }
}

