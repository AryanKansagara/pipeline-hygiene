import assert from 'node:assert/strict'
import { test } from 'node:test'
import { autoMap, detect, findHeaderRow, parseCsv, validate } from './csv.ts'

const read = (text: string) => { const t = findHeaderRow(parseCsv(text)), k = detect(t.rows[0]).kind; return validate(t, autoMap(t.rows[0], k), k) }
const errors = (text: string) => read(text).issues.filter(i => i.level === 'error').map(i => [i.line, i.message.slice(0, 20)])
const ACC = 'Account ID,Account Name,Website\n'
const OPP = 'Opportunity ID,Opportunity Name,Stage,Close Date,Amount\n'
const row = (id: string, name = id) => `${id},${name},Prospecting,12/15/2026,10\n`

test('sparse accounts at the end are kept', () => {
  assert.deepEqual(read(ACC + '001,Acme,acme.com\n002,Beta,\n003,Gamma,\n').parties.map(p => p.name), ['Acme', 'Beta', 'Gamma'])
})

test('deals whose names look like footers are kept', () => {
  const names = ['Copyright Clearance Center', 'Project Confidential', 'Grand Total Wines?', 'salesforce.com, inc', 'Total Wine', 'Totals Ltd', 'Generated by AI']
  for (const n of names) {
    const p = read(OPP + row('A') + row('B', `"${n}"`))
    assert.deepEqual(p.opps.map(o => o.name), ['A', n])
    // Also when the name is the first column.
    assert.equal(read('Opportunity Name,Stage,Close Date,Amount\nA,Prospecting,12/15/2026,1\n' + `"${n}",Prospecting,12/15/2026,1\n`).opps.length, 2, n)
  }
})

test('Salesforce footers are still dropped without a word', () => {
  for (const foot of ['"Grand Totals (1 record)"', '"Grand Totals (1 record)",,,,10', 'Total,,,,10', '"Confidential Information - Do Not Distribute"', '"Copyright (c) 2000-2026 salesforce.com, inc. All rights reserved."', '"Copyright © 2000-2026 salesforce.com, inc."', '"Generated By:  Ann Lee  11/6/2026"', 'Subtotal,', 'Count,,,,1', '"As of 11/6/2026"']) {
    for (const end of ['\n', '']) {
      const p = read(OPP + row('A') + '\n' + foot + end)
      assert.equal(p.opps.length, 1, foot)
      assert.deepEqual(p.issues.filter(i => i.level === 'error'), [], foot)
    }
  }
})

test('a row cut off at the end is reported with its line', () => {
  assert.deepEqual(errors(OPP + row('A') + 'B,Tw'), [[3, 'Only 2 of 5 columns.']])
  assert.deepEqual(errors(OPP + row('A') + 'B,Two,Prospecting,12/15/2026'), [[3, 'Only 4 of 5 columns.']])
  assert.equal(read(ACC + '001,Acme,acme.com\n002,Be').parties.length, 1)
})

test('a full last row without a line break is fine, with or without CRLF', () => {
  assert.equal(read((OPP + row('A') + row('B')).trimEnd()).opps.length, 2)
  assert.equal(read((OPP + row('A') + row('B')).replace(/\n/g, '\r\n').trimEnd()).opps.length, 2)
})

test('short rows that end properly keep importing', () => {
  assert.equal(read(ACC + '001,Acme\n002,Beta\n').parties.length, 2)
})

test('an unknown one-cell footer is listed, not imported', () => {
  const p = read('Account Name,Website,Phone\nAcme,acme.com,1\nPrepared for the board\n')
  assert.deepEqual(p.parties.map(x => x.name), ['Acme'])
  assert.equal(p.skipped, 1)
})

test('an unclosed quote is an error at the line it opens, and the swallowed rows are not a record', () => {
  const text = OPP + row('A') + row('B', '"Bee') + row('C') + row('D')
  assert.deepEqual(errors(text), [[3, 'A quote opened here ']])
  assert.deepEqual(read(text).opps.map(o => o.id), ['A'])
  assert.deepEqual(errors(OPP + row('A') + 'B,"Two, the'), [[3, 'A quote opened here ']])
})

test('closed quotes with line breaks inside are not affected', () => {
  assert.equal(read(OPP + row('A', '"Two\nlines"') + row('B', '"He said ""go"""')).opps.length, 2)
})
